/**
 * Generate the building image manifest.
 *
 * Scans client/public/assets/buildings/<age>/<nation>/<type>.png and writes
 * src/game/ui/buildingImageManifest.ts listing, per building type, the ages
 * for which a (romans) render exists. The catalog + canvas use this to load
 * and resolve sprites without probing for missing files.
 *
 * Run after adding/removing building art:
 *   node scripts/gen-building-manifest.mjs
 */

import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const BUILDINGS_DIR = join(ROOT, 'public', 'assets', 'buildings');
const OUT_FILE = join(ROOT, 'src', 'game', 'ui', 'buildingImageManifest.ts');
const NATION = 'romans';

// Canonical age order (mirrors shared/constants AGE_ORDER)
const AGE_ORDER = [
  'stone', 'bronze', 'iron', 'classical', 'medieval',
  'gunpowder', 'enlightenment', 'industrial', 'modern', 'digital',
];

function listPng(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.png')).map((f) => f.replace(/\.png$/, ''));
}

// type -> ordered list of ages that have art
const byType = {};
for (const age of AGE_ORDER) {
  const nationDir = join(BUILDINGS_DIR, age, NATION);
  for (const type of listPng(nationDir)) {
    (byType[type] ??= []).push(age);
  }
}

const sortedTypes = Object.keys(byType).sort();
const entries = sortedTypes
  .map((type) => `  ${type}: [${byType[type].map((a) => `'${a}'`).join(', ')}],`)
  .join('\n');

const banner = `// AUTO-GENERATED by scripts/gen-building-manifest.mjs — do not edit by hand.
// Lists, per building type, the ages for which a '${NATION}' sprite exists.
`;

const content = `${banner}
import type { Age, BuildingType } from '@shared/types';

export const BUILDING_IMAGE_AGES: Partial<Record<BuildingType, Age[]>> = {
${entries}
};
`;

writeFileSync(OUT_FILE, content);
console.log(`Wrote ${OUT_FILE}`);
console.log(`Building types with art: ${sortedTypes.length}`);
for (const type of sortedTypes) {
  console.log(`  ${type}: ${byType[type].join(', ')}`);
}
